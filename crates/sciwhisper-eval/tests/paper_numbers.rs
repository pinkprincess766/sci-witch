//! Every number the paper quotes comes from a published report.
//!
//! `paper/numbers.tex` is generated from `research/results/*.json` and this
//! test fails when the two disagree, so the paper cannot drift from the
//! measurements the way a hand-copied number does. After a report changes on
//! purpose, regenerate with
//! `PAPER_NUMBERS_WRITE=1 cargo test -p sciwhisper-eval --test paper_numbers`.

use std::fmt::Write as _;
use std::path::PathBuf;

fn root() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..")
}

fn report(name: &str) -> serde_json::Value {
    let path = root().join("research/results").join(name);
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|e| panic!("{}: {e}", path.display()))
}

fn int(value: &serde_json::Value, path: &str) -> u64 {
    value
        .pointer(path)
        .and_then(serde_json::Value::as_u64)
        .unwrap_or_else(|| panic!("{path} is not an unsigned integer"))
}

fn float(value: &serde_json::Value, path: &str) -> f64 {
    value
        .pointer(path)
        .and_then(serde_json::Value::as_f64)
        .unwrap_or_else(|| panic!("{path} is not a number"))
}

/// Three decimals, rounded up: an upper bound must never shrink by rounding.
fn upper(x: f64) -> String {
    format!("{:.3}", (x * 1000.0).ceil() / 1000.0)
}

/// The benchmark of `research/schema/compiler-gates-v2.json`, in its order,
/// with the macro prefix each report gets in the paper.
const BENCHMARK: [(&str, &str); 4] = [
    ("DevSeed", "deterministic-v6.json"),
    ("Ambiguous", "ambiguous-auto-v2.json"),
    ("Nomenclature", "nomenclature-v1.json"),
    ("Prose", "prose-negatives-v2.json"),
];

fn generate() -> String {
    let mut out = String::from(
        "% Generated by crates/sciwhisper-eval/tests/paper_numbers.rs from\n\
         % research/results/*.json. Do not edit by hand; regenerate with\n\
         % PAPER_NUMBERS_WRITE=1 cargo test -p sciwhisper-eval --test paper_numbers\n",
    );
    let mut ordinary = 0u64;
    let mut rewrites = 0u64;
    for (prefix, file) in BENCHMARK {
        let r = report(file);
        let fsrr = "/metrics/false_scientific_rewrite_rate";
        let exact = "/metrics/ast_exact_match";
        let line = |out: &mut String, name: &str, value: String| {
            writeln!(out, "\\newcommand{{\\{prefix}{name}}}{{{value}}}").unwrap();
        };
        line(&mut out, "Records", int(&r, "/dataset/records").to_string());
        line(
            &mut out,
            "ExactNum",
            int(&r, &format!("{exact}/numerator")).to_string(),
        );
        line(
            &mut out,
            "ExactDen",
            int(&r, &format!("{exact}/denominator")).to_string(),
        );
        line(
            &mut out,
            "RewriteNum",
            int(&r, &format!("{fsrr}/numerator")).to_string(),
        );
        line(
            &mut out,
            "RewriteDen",
            int(&r, &format!("{fsrr}/denominator")).to_string(),
        );
        line(
            &mut out,
            "RewriteUpper",
            upper(float(&r, &format!("{fsrr}/zero_count_upper95"))),
        );
        line(
            &mut out,
            "SFour",
            int(&r, "/severity/count_by_severity/S4").to_string(),
        );
        ordinary += int(&r, &format!("{fsrr}/denominator"));
        rewrites += int(&r, &format!("{fsrr}/numerator"));
    }
    // The pooled bound the compiler gates read: zero events in n trials.
    let bound = 1.0 - 0.05f64.powf(1.0 / ordinary as f64);
    writeln!(out, "\\newcommand{{\\PooledOrdinary}}{{{ordinary}}}").unwrap();
    writeln!(out, "\\newcommand{{\\PooledRewrites}}{{{rewrites}}}").unwrap();
    writeln!(
        out,
        "\\newcommand{{\\PooledUpper}}{{{:.4}}}",
        (bound * 10000.0).ceil() / 10000.0
    )
    .unwrap();

    let diff = report("grammar-differential-v1.json");
    let cells = diff
        .pointer("/cells")
        .and_then(|c| c.as_object())
        .expect("cells");
    let mut totals = [0u64; 5];
    let names = [
        "both_accept",
        "both_reject",
        "earley_only",
        "parser_only",
        "tokenize_fail",
    ];
    for modes in cells.values() {
        for cell in modes.as_object().expect("modes").values() {
            for (total, name) in totals.iter_mut().zip(names) {
                *total += cell.get(name).and_then(|v| v.as_u64()).expect(name);
            }
        }
    }
    for (macro_name, total) in [
        "DiffBothAccept",
        "DiffBothReject",
        "DiffEarleyOnly",
        "DiffParserOnly",
        "DiffTokenizeFail",
    ]
    .iter()
    .zip(totals)
    {
        writeln!(out, "\\newcommand{{\\{macro_name}}}{{{total}}}").unwrap();
    }

    // Parse-tree counts from grammar-differential-v2.json. Per corpus and mode
    // the buckets (1, 2, 3-10, above 10) partition the accepted runs, and the
    // accepted runs are the Earley-accepted cells of the same report. A wrong
    // JSON field breaks one of these sums, so the assertions below catch it.
    let v2 = report("grammar-differential-v2.json");
    let parse_counts = v2
        .pointer("/parse_counts")
        .and_then(|c| c.as_object())
        .expect("parse_counts");
    let v2_cells = v2
        .pointer("/cells")
        .and_then(|c| c.as_object())
        .expect("cells");
    // Buckets in the order: accepted, exact_1, exact_2, exact_3_to_10,
    // above_10, at_least_max.
    let mut parse = [0u64; 6];
    for (corpus, modes) in parse_counts {
        for (mode, c) in modes.as_object().expect("modes") {
            let accepted = int(c, "/accepted");
            let (one, two) = (int(c, "/exact_1"), int(c, "/exact_2"));
            let (three_ten, above) = (int(c, "/exact_3_to_10"), int(c, "/above_10"));
            let at_cap = int(c, "/at_least_max");
            assert_eq!(
                one + two + three_ten + above,
                accepted,
                "{corpus} {mode}: parse buckets do not sum to accepted"
            );
            assert!(
                at_cap <= above,
                "{corpus} {mode}: at_least_max is above_10 by definition"
            );
            let cell = v2_cells
                .get(corpus)
                .and_then(|m| m.get(mode))
                .unwrap_or_else(|| panic!("{corpus} {mode}: no cell"));
            assert_eq!(
                int(cell, "/both_accept") + int(cell, "/earley_only"),
                accepted,
                "{corpus} {mode}: accepted differs from the Earley-accepted cells"
            );
            for (total, value) in parse
                .iter_mut()
                .zip([accepted, one, two, three_ten, above, at_cap])
            {
                *total += value;
            }
        }
    }
    let [accepted, one, two, three_ten, above, at_cap] = parse;
    // Every run in the report, the denominator of the grammar comparison.
    let mut runs = 0u64;
    for modes in v2_cells.values() {
        for cell in modes.as_object().expect("modes").values() {
            for name in names {
                runs += int(cell, &format!("/{name}"));
            }
        }
    }
    let largest = v2
        .pointer("/most_parses")
        .and_then(|m| m.as_array())
        .expect("most_parses")
        .iter()
        .map(|e| int(e, "/count"))
        .max()
        .expect("most_parses is empty");
    let cap = int(&v2, "/max_parses");
    assert!(largest <= cap, "most_parses count above max_parses");
    for (macro_name, value) in [
        ("ParseAccepted", accepted),
        ("ParseOne", one),
        ("ParseTwo", two),
        ("ParseThreeToTen", three_ten),
        ("ParseAboveTen", above),
        ("ParseAtCap", at_cap),
        ("ParseRuns", runs),
        ("ParseLargest", largest),
        ("ParseCap", cap),
    ] {
        writeln!(out, "\\newcommand{{\\{macro_name}}}{{{value}}}").unwrap();
    }
    out
}

#[test]
fn the_paper_quotes_the_published_reports() {
    let path = root().join("paper/numbers.tex");
    let live = generate();
    if std::env::var_os("PAPER_NUMBERS_WRITE").is_some() {
        std::fs::write(&path, &live).unwrap_or_else(|e| panic!("{}: {e}", path.display()));
        return;
    }
    let stored = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "{}: {e}; generate it with PAPER_NUMBERS_WRITE=1 cargo test -p sciwhisper-eval --test paper_numbers",
            path.display()
        )
    });
    // Line endings may be CRLF on a Windows checkout; the numbers may not differ.
    assert_eq!(
        stored.replace("\r\n", "\n"),
        live,
        "paper/numbers.tex is out of date with research/results; regenerate it"
    );
}

/// The other side: a paper that hard-codes a number instead of using the
/// macro would pass the test above. Every macro defined in numbers.tex is
/// therefore expected to be used by main.tex, and main.tex may not quote the
/// pooled denominator as a literal.
#[test]
fn the_paper_uses_the_macros_rather_than_literals() {
    let main = std::fs::read_to_string(root().join("paper/main.tex")).expect("paper/main.tex");
    let live = generate();
    let pooled = live
        .lines()
        .find_map(|l| l.strip_prefix("\\newcommand{\\PooledOrdinary}{"))
        .and_then(|l| l.strip_suffix('}'))
        .expect("PooledOrdinary");
    assert!(
        !main.contains(&format!(" {pooled} ")),
        "main.tex quotes {pooled} literally; use \\PooledOrdinary"
    );
    for name in [
        "PooledOrdinary",
        "PooledUpper",
        "ProseRewriteDen",
        "DiffParserOnly",
    ] {
        assert!(
            main.contains(&format!("\\{name}")),
            "main.tex does not use \\{name}"
        );
    }
}
