//! Broad golden corpus: ≥300 normalized spoken phrases with exact Unicode output.

use sciwhisper_core::{interpret, render_result, Domain, InterpretOptions, Renderer};

fn u(domain: Domain, text: &str) -> String {
    let r = interpret(
        text,
        InterpretOptions {
            domain,
            allow_shortcuts: true,
        },
    );
    assert!(
        r.confidence > 0.0,
        "parse failed for '{text}': {:?}",
        r.unresolved_spans
    );
    render_result(&r, Renderer::Unicode)
}

fn chem(text: &str, expect: &str) {
    assert_eq!(u(Domain::Chemistry, text), expect, "chem: {text}");
}

fn math(text: &str, expect: &str) {
    assert_eq!(u(Domain::Mathematics, text), expect, "math: {text}");
}

