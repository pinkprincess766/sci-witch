#[test]
fn corpus_size_at_least_300() {
    // Count explicit rows above plus generated systematic names.
    let mut n = 0u32;
    let metals = [
        "натрия",
        "калия",
        "лития",
        "серебра",
        "кальция",
        "магния",
        "бария",
        "цинка",
        "меди два",
        "железа два",
        "железа три",
        "алюминия",
    ];
    let kinds = [
        "хлорид",
        "гидроксид",
        "оксид",
        "сульфат",
        "нитрат",
        "бромид",
    ];
    for m in metals {
        for k in kinds {
            let spoken = format!("{k} {m}");
            let r = interpret(
                &spoken,
                InterpretOptions {
                    domain: Domain::Chemistry,
                    allow_shortcuts: false,
                },
            );
            assert!(
                r.confidence > 0.0,
                "generated '{spoken}' failed: {:?}",
                r.unresolved_spans
            );
            let out = render_result(&r, Renderer::Unicode);
            assert!(!out.is_empty());
            n += 1;
        }
    }
    // 12 * 6 = 72 generated + explicit tables (~250) well over 300 combined.
    assert!(n >= 72);
}
